const Lang = {
  current: (() => {
    try { return localStorage.getItem("3urfti.lang") === "ar" ? "ar" : "en"; } catch { return "en"; }
  })(),

  // Look up one piece of text, e.g. t("card.match", { n: 87 }) → "87% match"
  t(key, vars = {}) {
    let text = I18N[this.current][key] ?? I18N.en[key] ?? key;
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
    return text;
  },

  // Switch the whole page to "en" or "ar"
  apply(lang) {
    this.current = lang;
    try { localStorage.setItem("3urfti.lang", lang); } catch {}

    const html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr"; // RTL = right-to-left for Arabic

    document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = this.t(el.dataset.i18n); });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = this.t(el.dataset.i18nHtml); });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = this.t(el.dataset.i18nPlaceholder); });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(el.dataset.i18nAria));
      el.title = this.t(el.dataset.i18nAria);
    });

    // Tell the page scripts so they can redraw cards, lists, etc.
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
  },

  toggle() { this.apply(this.current === "en" ? "ar" : "en"); },
};

const t = (key, vars) => Lang.t(key, vars);

// Pick the right language from an { en, ar } object
function loc(value) {
  if (!value) return "";
  if (typeof value === "string") return value;
  return value[Lang.current] || value.en || "";
}

document.addEventListener("click", (e) => {
  if (e.target.closest("[data-lang-toggle]")) Lang.toggle();
});
document.addEventListener("DOMContentLoaded", () => Lang.apply(Lang.current));
